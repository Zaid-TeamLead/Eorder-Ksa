-- 100036: Get active lenders
-- DROP PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100036_EORDER";
CREATE PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100036_EORDER" ()
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN
  SELECT *
  FROM "BI_NEGT_KSAISUZU"."DMS_LENDERS"
  WHERE "IS_ACTIVE" = 'Y'
  ORDER BY "LENDER_NAME";
END;

-- 100037: Set preferred financing scheme
-- DROP PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100037_EORDER";
CREATE PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100037_EORDER" (
  IN I_SLNO INTEGER,
  IN I_ENQUIRY_SLNO INTEGER,
  IN I_UPDATED_BY NVARCHAR(100),
  IN I_UPDATED_DATE NVARCHAR(19)
)
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN
  UPDATE "BI_NEGT_KSAISUZU"."DMS_ENQUIRY_FINANCING"
  SET "IS_SELECTED" = 'N',
      "UPDATED_BY" = :I_UPDATED_BY,
      "UPDATED_DATE" = TO_TIMESTAMP(:I_UPDATED_DATE, 'YYYY-MM-DD HH24:MI:SS')
  WHERE "ENQUIRY_SLNO" = :I_ENQUIRY_SLNO
    AND "IS_DELETED" = 'N';

  UPDATE "BI_NEGT_KSAISUZU"."DMS_ENQUIRY_FINANCING"
  SET "IS_SELECTED" = 'Y',
      "UPDATED_BY" = :I_UPDATED_BY,
      "UPDATED_DATE" = TO_TIMESTAMP(:I_UPDATED_DATE, 'YYYY-MM-DD HH24:MI:SS')
  WHERE "SLNO" = :I_SLNO
    AND "IS_DELETED" = 'N';
END;

