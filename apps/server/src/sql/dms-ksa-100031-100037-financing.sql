-- 100031: Get financing schemes by enquiry
-- DROP PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100031_EORDER";
CREATE PROCEDURE "BI_NEGT_KSAISUZU"."DMS_KSA_100031_EORDER" (
  IN I_ENQUIRY_SLNO INTEGER
)
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN
  SELECT *
  FROM "BI_NEGT_KSAISUZU"."DMS_ENQUIRY_FINANCING"
  WHERE "ENQUIRY_SLNO" = :I_ENQUIRY_SLNO
    AND "IS_DELETED" = 'N'
  ORDER BY "CREATED_DATE" DESC;
END;

